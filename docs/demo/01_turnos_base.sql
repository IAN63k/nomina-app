-- =============================================================================
-- Proyecto Supabase DEMO — tablas base de turnos (Recargos)
-- =============================================================================
-- En producción turnos_medicos, turnos_auxiliares y turnos_medicos_trash se
-- crearon a mano antes de los scripts de docs/. Aquí se recrean con la forma
-- actual (PK (medico, fecha_inicio, concepto)) para poder levantar un proyecto
-- desde cero. Orden completo en docs/demo/README.md.
-- =============================================================================

create table if not exists public.turnos_medicos (
  id            bigint generated by default as identity,
  medico        text        not null,
  documento     bigint,
  fecha         date        not null,
  fecha_inicio  date        not null,
  turno_codigo  text        default ''::text,
  entrada       text,
  salida        text,
  concepto      integer     not null default 0,
  horas         numeric     default 0,
  horasrecargo  numeric     default 0,
  diferencia    numeric     default 0,
  dia           text,
  mes           integer,
  dia_numero    integer,
  created_at    timestamptz default now(),
  primary key (medico, fecha_inicio, concepto)
);
create index if not exists turnos_medicos_fecha_inicio_idx on public.turnos_medicos (fecha_inicio);

create table if not exists public.turnos_auxiliares (
  medico        text        not null,
  documento     bigint,
  fecha         date        not null,
  fecha_inicio  date        not null,
  turno_codigo  text        default ''::text,
  entrada       text,
  salida        text,
  concepto      integer     not null default 0,
  horas         numeric     default 0,
  horasrecargo  numeric     default 0,
  diferencia    numeric     default 0,
  dia           text,
  mes           integer,
  dia_numero    integer,
  festivo       boolean     default false,
  created_at    timestamptz default now(),
  primary key (medico, fecha_inicio, concepto)
);
create index if not exists turnos_auxiliares_mes_idx on public.turnos_auxiliares (mes);
create index if not exists turnos_auxiliares_medico_idx on public.turnos_auxiliares (medico);

-- Papelera de médicos (la de auxiliares la crea docs/turnos_trash.sql).
create table if not exists public.turnos_medicos_trash (
  id            bigint generated by default as identity primary key,
  original_id   bigint,
  medico        text        not null,
  documento     bigint,
  fecha         date        not null,
  fecha_inicio  date,
  turno_codigo  text        default ''::text,
  entrada       text,
  salida        text,
  concepto      integer     not null default 0,
  horas         numeric     default 0,
  horasrecargo  numeric     default 0,
  diferencia    numeric     default 0,
  dia           char(1)     check (dia in ('D', 'H', 'S')),
  mes           integer,
  dia_numero    integer,
  created_at    timestamptz,
  deleted_by    text,
  deleted_at    timestamptz not null default now()
);
create index if not exists idx_turnos_trash_medico on public.turnos_medicos_trash (medico);
